function buttonClicked(){

    document.getElementById("message").innerHTML =
    "Button Clicked Successfully!";

}

function showText(value){

    document.getElementById("message").innerHTML =
    "Hello, " + value;

}

function mouseOver(){

    document.getElementById("message").innerHTML =
    "Mouse is over the box.";

}

function mouseOut(){

    document.getElementById("message").innerHTML =
    "Mouse left the box.";

}
